        private const val TAG = "Ts8MapLibre"

        const val ROUTE_OVERLAY = "ts8-route"
        const val ALT_ROUTE_OVERLAY = "ts8-alt-routes"
        const val VEHICLE_OVERLAY = "ts8-vehicle"
        const val DESTINATION_OVERLAY = "ts8-destination"
        const val TRAFFIC_SIGN_OVERLAY = "ts8-traffic-signs"

        const val LAYER_ALT_ROUTE = "ts8-alt-route"
        const val LAYER_ROUTE_CASING = "ts8-route-casing"
        const val LAYER_ROUTE_LINE = "ts8-route-line"
        const val LAYER_DESTINATION = "ts8-destination-layer"
        const val LAYER_VEHICLE_HALO = "ts8-vehicle-halo"
        const val LAYER_VEHICLE = "ts8-vehicle-layer"
        const val LAYER_TRAFFIC_SIGN = "ts8-traffic-sign-layer"

        const val PIN_IMAGE = "ts8-pin"
        const val VEHICLE_IMAGE = "ts8-vehicle"

        /**
         * Boolean feature property that marks the driven half of the route.
         *
         * Named once here rather than repeated in `drawRoute` and in the two
         * layer expressions: a typo on either side would not fail to compile,
         * it would silently paint the whole line at full opacity and the split
         * would just never appear (§8).
         */
        const val PROP_TRAVELLED = "travelled"

        private const val NAV_ZOOM = 17.0
        private const val NAV_ZOOM_TILT = 17.5
        private const val NAV_TILT = 45f

        /**
         * Zoom difference that counts as "the driver moved it".
         *
         * A button press moves exactly one level, so half a level is the natural
         * boundary: it is under any deliberate change and over the error of
         * sampling the camera mid-animation, which is how this could otherwise
         * latch a value the driver never asked for. Pinches smaller than this
         * are still adopted, because the camera-idle listener sets the override
         * directly from the settled camera.
         */
        private const val ZOOM_EPSILON = 0.5

        /**
         * How far the camera target must travel during a gesture to count as a
         * pan rather than a pinch.
         *
         * A pinch leaves the target essentially where the follow camera put it
         * (a few metres of drift at most). A pan is a deliberate drag across the
         * panel, which at any usable zoom moves the target by hundreds of
         * metres. The gap between those two is wide, and 60 m sits in it with
         * room for the car's own travel during the second or so a gesture lasts.
         */
        private const val PAN_GESTURE_METRES = 60.0
    }
